CREATE TABLE IF NOT EXISTS `DATA_ACCESS_REQUEST` (
  `ID` BIGINT NOT NULL,
  `ACCESS_REQUIREMENT_ID` BIGINT NOT NULL,
  `RESEARCH_PROJECT_ID` BIGINT DEFAULT NULL,
  `CREATED_BY` BIGINT NOT NULL,
  `CREATED_ON` BIGINT NOT NULL,
  `MODIFIED_BY` BIGINT NOT NULL,
  `MODIFIED_ON` BIGINT NOT NULL,
  `ETAG` char(36) NOT NULL,
  `CONCRETE_TYPE` VARCHAR(255) NOT NULL,
  `ACCESS_REQUIREMENT_VERSION_NUMBER` BIGINT DEFAULT NULL,
  `DUC_FILE_HANDLE_ID` BIGINT DEFAULT NULL,
  `IRB_FILE_HANDLE_ID` BIGINT DEFAULT NULL,
  `ATTACHMENTS` JSON DEFAULT NULL,
  `ACCESSOR_CHANGES` JSON DEFAULT NULL,
  `INSTITUTION` MEDIUMTEXT DEFAULT NULL,
  `PRINCIPAL_INVESTIGATOR` JSON DEFAULT NULL,
  `SIGNING_OFFICIAL` JSON DEFAULT NULL,
  `SCHEMA_DATA` JSON DEFAULT NULL,
  `SCHEMA_DATA_ATTACHMENTS` JSON DEFAULT NULL,
  `PUBLICATION` MEDIUMTEXT DEFAULT NULL,
  `SUMMARY_OF_USE` MEDIUMTEXT DEFAULT NULL,
  `EDUC_ENVELOPE_ID` VARCHAR(255) DEFAULT NULL,
  `EDUC_CONTENT_HASH` VARCHAR(64) DEFAULT NULL,
  PRIMARY KEY (`ID`),
  UNIQUE KEY `ACCESS_REQUIREMENT_ID_AND_CREATED_BY` (`ACCESS_REQUIREMENT_ID`, `CREATED_BY`),
  CONSTRAINT `DATA_ACCESS_REQUEST_ACCESS_REQUIREMENT_ID_FK` FOREIGN KEY (`ACCESS_REQUIREMENT_ID`) REFERENCES `ACCESS_REQUIREMENT` (`ID`) ON DELETE RESTRICT,
  CONSTRAINT `DATA_ACCESS_REQUEST_RESEARCH_PROJECT_ID_FK` FOREIGN KEY (`RESEARCH_PROJECT_ID`) REFERENCES `RESEARCH_PROJECT` (`ID`) ON DELETE RESTRICT
)
